// Helper function to get posts by designer
export const getPostsByDesigner = (designerId: string): DesignerPost[] => {
  return designerPosts.filter((post) => post.designerId === designerId);
};

// Helper function to get posts for followed designers
export const getFollowingPosts = (followedDesignerIds: Set<string>): DesignerPost[] => {
  return designerPosts
    .filter((post) => followedDesignerIds.has(post.designerId))
    .sort((a, b) => b.timestamp - a.timestamp); // Most recent first
};
